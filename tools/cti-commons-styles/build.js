/* eslint-env node */
/* eslint-disable import/no-dynamic-require, global-require, no-console */
/*
 * Regenerates the cti-commons styles from aem-cti-commons/ui.frontend (same Sass, autoprefixer
 * and cssnano as its webpack prod build): site CSS into styles/cti-commons, Content Block CSS
 * into its block.
 * Usage: node tools/cti-commons-styles/build.js <path to aem-cti-commons/ui.frontend>
 * styles/cti-commons/css/base.min.css is the clientlib-base CSS (Core Components) served by AEM.
 */
const path = require('path');
const fs = require('fs');

const FE = path.resolve(process.argv[2] || '');
const SRC = `${FE}/src/main/webpack`;
const SITE = `${SRC}/site`;
const EDS = path.resolve(__dirname, '../..');
const BLOCK = '../components/content-block/_content-block.scss';
const EDS_BLOCK_RULE = `
/* EDS equivalent of the rule above (the AEM grid wrapper is the section, the component wrapper is the block wrapper) */
.section > .content-block-wrapper:first-child > .content-block > .content-block.row:not(.content-block--corporate) {
  margin-top: 40px;
}
`;

if (!fs.existsSync(`${SITE}/main.scss`)) throw new Error(`Not an aem-cti-commons ui.frontend: ${FE}`);

const req = (m) => require(`${FE}/node_modules/${m}`);
const sass = req('sass');
const glob = req('glob');
const postcss7 = req('postcss-loader/node_modules/postcss');
const autoprefixer = req('autoprefixer');
const postcss8 = req('postcss');
const cssnano = req('cssnano');

// same order as site/main.scss (glob-import-loader expands the globs with glob.sync)
const components = glob.sync('../components/**/*.scss', { cwd: SITE });
const styles = glob.sync('./styles/*.scss', { cwd: SITE });
const imp = (list) => list.map((f) => `@import '${path.resolve(SITE, f)}';`).join('\n');
const siteEntry = [
  "@import 'variables';", "@import 'fonts';", "@import 'base';", "@import '../legacy/clv-wem-bk';",
  imp(components.filter((f) => f !== BLOCK)), imp(styles),
].join('\n');

const compile = (data) => sass.compileString(data, {
  loadPaths: [SITE],
  url: new URL(`file://${SITE}/main.scss`),
  quietDeps: true,
  logger: sass.Logger.silent,
}).css;
const prefix = async (css) => (await postcss7([autoprefixer({ overrideBrowserslist: ['last 2 version', '> 1%'] })])
  .process(css, { from: undefined })).css;
const minify = async (css) => (await postcss8([cssnano({
  preset: ['default', {
    calc: true,
    convertValues: true,
    discardComments: { removeAll: true },
    discardDuplicates: true,
    discardEmpty: true,
    mergeRules: true,
    normalizeCharset: true,
    reduceInitial: true,
    svgo: true,
  }],
})]).process(css, { from: undefined })).css;

(async () => {
  const out = `${EDS}/styles/cti-commons`;
  fs.mkdirSync(`${out}/css`, { recursive: true });
  fs.rmSync(`${out}/resources`, { recursive: true, force: true });
  fs.cpSync(`${SRC}/resources`, `${out}/resources`, { recursive: true, filter: (f) => !f.endsWith('.gitkeep') });

  fs.writeFileSync(`${out}/css/site.min.css`, await minify(await prefix(compile(siteEntry))));

  const block = (await prefix(compile(imp([BLOCK])))).replace(/url\(\.\.\/resources\//g, 'url(/styles/cti-commons/resources/');
  fs.writeFileSync(
    `${EDS}/blocks/content-block/content-block.css`,
    `/* stylelint-disable */\n/* Generated by tools/cti-commons-styles/build.js from components/content-block/_content-block.scss. */\n${block}${EDS_BLOCK_RULE}`,
  );
  console.log('cti-commons styles generated');
})();
